// 左移 每一位向左移动，末尾补0
let a = 0b000100 // 4
console.log(a << 1) // 8

// 右移
// 有符号右移
// 移动的时候高位补的是符号位 整数补0 负数补1
let b = 0b000111 // 7
console.log(b >> 1) // 3

let c = -4
// 补码 11111100
// 11111110
// 11111110 -> -1  ->  11111101 取反 ->  10000010 也就是-2
console.log(c >> 1) // -2

// 无符号右移
// 右移的时候最高位始终补0
// 正数不变
// 负数的话会变成正数
let d = 0b00000111
console.log(d >>> 1) // 3

let e = 0b10000111
console.log(e >>> 1) // 67
